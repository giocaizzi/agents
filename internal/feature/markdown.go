package feature

import (
	"bytes"
	"fmt"
	"slices"
	"strings"
)

// DisplayName is the name of harness h in prose and table headers.
func DisplayName(h string) string {
	switch h {
	case claude:
		return "Claude Code"
	case copilot:
		return "Copilot CLI"
	case vscode:
		return "VS Code"
	case codex:
		return "Codex"
	case opencode:
		return "opencode"
	case pi:
		return "pi"
	case antigravity:
		return "Antigravity"
	}
	return h
}

// Markdown renders the feature matrix document (docs/features.md).
func Markdown() []byte {
	var b bytes.Buffer
	b.WriteString(intro)

	b.WriteString("\n## Matrix\n\n")
	header := make([]string, 0, len(HarnessIDs())+1)
	rule := make([]string, 0, len(HarnessIDs())+1)
	header, rule = append(header, "Key"), append(rule, "---")
	for _, h := range HarnessIDs() {
		header = append(header, DisplayName(h))
		rule = append(rule, ":-:")
	}
	fmt.Fprintf(&b, "| %s |\n| %s |\n", strings.Join(header, " | "), strings.Join(rule, " | "))
	for _, f := range Features {
		if f.Scope == ScopeInternal {
			continue
		}
		row := make([]string, 0, len(HarnessIDs())+1)
		row = append(row, "`"+f.Key+"`")
		for _, h := range HarnessIDs() {
			row = append(row, symbol(f.Cells, h))
		}
		fmt.Fprintf(&b, "| %s |\n", strings.Join(row, " | "))
	}

	b.WriteString("\n## Internal keys\n\nThese keys steer agents itself and are never written to a harness:\n\n")
	for _, f := range Features {
		if f.Scope == ScopeInternal {
			fmt.Fprintf(&b, "- `%s`: %s\n", f.Key, f.Summary)
		}
	}

	b.WriteString("\n## Per harness\n")
	for _, h := range HarnessIDs() {
		harnessNotes(&b, h)
	}

	b.WriteString("\n## Planned\n\nThe harness supports the setting natively and agents does not write it yet. `agents check` warns when such a key is set.\n\n")
	for _, f := range Planned() {
		for _, h := range f.Harnesses(StatusPlanned) {
			fmt.Fprintf(&b, "- `%s` on %s: %s\n", f.Key, DisplayName(h), Detail(h, f.Cells[h]))
		}
	}
	return b.Bytes()
}

const intro = `# Feature matrix

<!-- Generated by go test ./internal/feature -run TestDocsDrift -update from internal/feature/table.go. Do not edit by hand. -->

Which configuration keys each harness supports. Every key is in one of three states per harness:

- ✓ **rendered**: ` + "`agents apply`" + ` writes the key to the harness (the target is listed under the harness below).
- — **unsupported**: the harness has no native setting for it, so the key has no effect there. ` + "`agents check`" + ` reports it as info.
- planned: the harness has a native setting that agents does not write yet. ` + "`agents check`" + ` warns.

The table is Go code (` + "`internal/feature`" + `); it also feeds the descriptions in the JSON Schema, ` + "`agents check`" + ` and ` + "`agents features`" + `. A key blank in the matrix belongs to another harness's own table (` + "`harness.<name>.*`" + `). A ` + "`*`" + ` in a key stands for a free name. See [parity.md](parity.md) for how each rendered key is translated.
`

// symbol is the matrix cell of harness h.
func symbol(cells map[string]Cell, h string) string {
	c, ok := cells[h]
	switch {
	case !ok:
		return ""
	case c.Status == StatusRendered:
		return "✓"
	case c.Status == StatusUnsupported:
		return "—"
	}
	return "planned"
}

// harnessNotes writes the targets, planned keys and evidence of harness h.
func harnessNotes(b *bytes.Buffer, h string) {
	fmt.Fprintf(b, "\n### %s\n\nDocumentation checked in %s: %s\n", DisplayName(h), Checked, Source(h))

	var rendered, planned []string
	unsupported := map[string][]string{}
	var details []string
	for _, f := range Features {
		c, ok := f.Cells[h]
		if !ok {
			continue
		}
		switch c.Status {
		case StatusRendered:
			rendered = append(rendered, fmt.Sprintf("- `%s`: %s", f.Key, targets(c.Target)))
		case StatusPlanned:
			planned = append(planned, fmt.Sprintf("- `%s`: %s", f.Key, Detail(h, c)))
		case StatusUnsupported:
			d := Detail(h, c)
			if _, seen := unsupported[d]; !seen {
				details = append(details, d)
			}
			unsupported[d] = append(unsupported[d], "`"+f.Key+"`")
		}
	}
	section := func(title string, lines []string) {
		if len(lines) > 0 {
			fmt.Fprintf(b, "\n**%s**\n\n%s\n", title, strings.Join(lines, "\n"))
		}
	}
	section("Rendered", rendered)
	section("Planned", planned)
	slices.Sort(details)
	lines := make([]string, 0, len(details))
	for _, d := range details {
		lines = append(lines, fmt.Sprintf("- %s: %s", d, strings.Join(unsupported[d], ", ")))
	}
	section("Not supported", lines)
}

// targets formats a cell target for a list item.
func targets(t string) string {
	parts := strings.Split(t, "; ")
	for i, p := range parts {
		parts[i] = "`" + p + "`"
	}
	return strings.Join(parts, ", ")
}
